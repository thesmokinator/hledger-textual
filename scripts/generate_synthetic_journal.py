#!/usr/bin/env python3
"""Generate a synthetic hledger journal for performance measurements.

The output is deterministic for a given seed, so timings collected on
different machines can be compared on equivalent data.

Examples:
    python scripts/generate_synthetic_journal.py --transactions 50000
    python scripts/generate_synthetic_journal.py -n 100000 -o /tmp/big.journal
"""

from __future__ import annotations

import argparse
import random
from datetime import date, timedelta
from pathlib import Path

DESCRIPTIONS = (
    "Groceries",
    "Coffee",
    "Lunch",
    "Fuel",
    "Train ticket",
    "Pharmacy",
    "Books",
    "Cinema",
    "Home supplies",
    "Dinner",
    "Taxi",
    "Subscription",
)

EXPENSE_CATEGORIES = (
    "food",
    "transport",
    "housing",
    "health",
    "entertainment",
    "shopping",
    "education",
    "travel",
)


def generate_journal(
    output: str | Path,
    transactions: int = 50_000,
    *,
    seed: int = 42,
    start: date = date(2015, 1, 1),
    end: date | None = None,
    commodity: str = "EUR",
) -> Path:
    """Write a synthetic journal and return its path.

    Args:
        output: Destination path.
        transactions: Exact number of transactions to generate.
        seed: Seed for the deterministic pseudo-random generator.
        start: First date that may receive transactions.
        end: Last date that may receive transactions (default: today).
        commodity: Commodity symbol used for every amount.

    Returns:
        The path written.

    Raises:
        ValueError: When ``transactions`` is negative or the date range is
            empty.
    """
    if transactions < 0:
        raise ValueError("transactions must be >= 0")
    if end is None:
        end = date.today()
    if end < start:
        raise ValueError("end must not be before start")

    rng = random.Random(seed)
    path = Path(output)
    path.parent.mkdir(parents=True, exist_ok=True)

    expenses = [
        f"expenses:{category}:{account}"
        for category in EXPENSE_CATEGORIES
        for account in ("general", "other")
    ]
    accounts = (
        ["assets:bank:checking", "assets:bank:savings", "income:salary"]
        + expenses
    )

    span_days = (end - start).days
    dates = sorted(
        start + timedelta(days=rng.randrange(span_days + 1))
        for _ in range(transactions)
    )

    lines = [
        "; Synthetic journal generated by scripts/generate_synthetic_journal.py",
        f"; transactions: {transactions}, seed: {seed}",
        "",
        f"commodity 1,000.00 {commodity}",
        "account assets:bank:checking",
        "account assets:bank:savings",
    ]
    lines.extend(f"account {account}" for account in accounts[2:])
    lines.append("")

    for index, txn_date in enumerate(dates):
        if index % 12 == 0:
            amount = f"{rng.randint(1800, 4200)}.00 {commodity}"
            lines.extend(
                [
                    f"{txn_date.isoformat()} Salary payment {index}",
                    f"    assets:bank:checking    {amount}",
                    "    income:salary",
                    "",
                ]
            )
            continue

        account = rng.choice(expenses)
        amount = f"{rng.randint(100, 90_000) / 100:.2f} {commodity}"
        payee = rng.choice(DESCRIPTIONS)
        lines.extend(
            [
                f"{txn_date.isoformat()} {payee} {index}",
                f"    {account}    {amount}",
                "    assets:bank:checking",
                "",
            ]
        )

    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return path


def _parse_date(value: str) -> date:
    """Parse an ISO date for argparse."""
    return date.fromisoformat(value)


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-n",
        "--transactions",
        type=int,
        default=50_000,
        help="number of transactions to generate (default: 50000)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("synthetic.journal"),
        help="output journal path (default: ./synthetic.journal)",
    )
    parser.add_argument(
        "--seed", type=int, default=42, help="random seed (default: 42)"
    )
    parser.add_argument(
        "--start",
        type=_parse_date,
        default=date(2015, 1, 1),
        help="first transaction date, YYYY-MM-DD (default: 2015-01-01)",
    )
    parser.add_argument(
        "--end",
        type=_parse_date,
        default=None,
        help="last transaction date, YYYY-MM-DD (default: today)",
    )
    parser.add_argument(
        "--commodity",
        default="EUR",
        help="commodity symbol (default: EUR)",
    )
    args = parser.parse_args(argv)

    path = generate_journal(
        args.output,
        args.transactions,
        seed=args.seed,
        start=args.start,
        end=args.end,
        commodity=args.commodity,
    )
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
